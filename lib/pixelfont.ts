export const GLYPH_W = 5;
export const GLYPH_H = 7;
const glyphs: Record<string, string[]> = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(' ')]));

/** One word → SVG rect runs, merged per row. Unknown chars render as blanks. */
export function wordRects(word: string) {
  const chars = Array.from(word.toUpperCase());
  const rects: { x: number; y: number; w: number }[] = [];
  chars.forEach((ch, i) => {
    const g = glyphs[ch];
    if (!g) return;
    const x0 = i * (GLYPH_W + 1);
    for (let r = 0; r < GLYPH_H; r++) {
      let run = 0;
      for (let c = 0; c <= GLYPH_W; c++) {
        if (g[r][c] === '1') {
          run++;
          continue;
        }
        if (run) rects.push({ x: x0 + c - run, y: r, w: run });
        run = 0;
      }
    }
  });
  const cols = Math.max(1, chars.length * (GLYPH_W + 1) - 1);
  return { rects, cols };
}

/** Raw rows for one glyph (for canvas drawing). */
export const glyph = (ch: string): string[] | undefined => glyphs[ch.toUpperCase()];
